/** The demo scenes the tour starts itself. */
export type TourScene = "milk" | "over-limit" | "break-mandate";

const RUN_SLOT = /\{run:([a-z-]+)\}/g;

/**
 * The run blocks of the run the tour started for `scene`. The id is filled in by `resolveTargets` from the run id
 * the start call returned, so the spotlight finds that run and never another one.
 */
export function runOf(scene: TourScene): string {
  return `[data-tour="runs"] .run[data-demo-run="{run:${scene}}"]`;
}

/** Fills each selector's run slot with the tour's own run id; a selector whose run has not started yet is left out. */
export function resolveTargets(selectors: readonly string[], runs: Partial<Record<string, string>>): string[] {
  return selectors.flatMap((selector) => {
    let missing = false;
    const resolved = selector.replace(RUN_SLOT, (_, scene: string) => {
      const id = runs[scene];
      if (!id) missing = true;
      return id ? cssSafe(id) : "";
    });
    return missing ? [] : [resolved];
  });
}

/** Run ids are generated by the server as letters, digits, "_" and "-"; anything else is dropped from a selector. */
function cssSafe(id: string): string {
  return id.replace(/[^A-Za-z0-9_-]/g, "");
}
